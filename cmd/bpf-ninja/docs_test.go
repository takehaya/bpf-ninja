var updateDocs = flag.Bool("update-docs", false, "update generated CLI and protocol references")

// Each help invocation gets a fresh command graph. Running --help initializes
// urfave's built-in help/version/completion commands and inherited flags without
// running capture, conversion or map operations. Guard application actions so a
// change in help handling fails the generator rather than doing real work.
func docsCommand(t *testing.T, path []string) (*cli.Command, string) {
	t.Helper()
	root := newRootCommand()
	root.Version = "source checkout"
	var guard func(*cli.Command)
	guard = func(cmd *cli.Command) {
		cmd.Action = func(context.Context, *cli.Command) error {
			return fmt.Errorf("documentation attempted to execute %s", cmd.Name)
		}
		for _, child := range cmd.Commands {
			guard(child)
		}
	}
	guard(root)
	var out bytes.Buffer
	root.Writer, root.ErrWriter = &out, &out
	args := append([]string{root.Name}, path...)
	args = append(args, "--help")
	if err := root.Run(context.Background(), args); err != nil {
		t.Fatalf("help for %v: %v", path, err)
	}
	cmd := root
	for _, name := range path {
		cmd = cmd.Command(name)
		if cmd == nil {
			t.Fatalf("command missing: %v", path)
		}
	}
	return cmd, out.String()
}

func docsCell(s string) string {
	s = html.EscapeString(s)
	s = strings.ReplaceAll(s, "|", "&#124;")
	s = strings.ReplaceAll(s, "\n", "<br>")
	return "<code>" + s + "</code>"
}

func commandReference(t *testing.T) []byte {
	t.Helper()
	var out bytes.Buffer
	out.WriteString("# CLI reference\n\n<!-- Generated by cmd/bpf-ninja/docs_test.go; do not edit. -->\n\n")
	out.WriteString("`make docs-update` で更新し、`make docs-check` で生成元との差分を検査します。\n")
	out.WriteString("この文書を含むソースのコマンド定義と urfave/cli の help から生成しています。\n")
	out.WriteString("説明文は CLI と共通の英語です。[読み方と操作上の制約](../README.md)も参照してください。\n\n")
	out.WriteString("表の必須列は flag metadata の Required を示します。\nAction 内の入力検査は表に含まれません。\n")
	out.WriteString("複数値列は slice/map flag が複数の値を受け付けるかを示します。\nmode などの組合せ条件は、操作上の制約を確認してください。\n")
	out.WriteString("各表には、そのコマンドの公開 flag を記載します。\nhelp ブロックには、継承した flag を含む実際の help 出力を記録します。\n")
	out.WriteString("非表示の flag と completion command は一覧の対象外です。\n組込みの `help [command]` / `--help` も利用できます。\n\n")
	var visit func([]string)
	visit = func(path []string) {
		cmd, help := docsCommand(t, path)
		name := strings.Join(append([]string{"bpf-ninja"}, path...), " ")
		fmt.Fprintf(&out, "## %s\n\n```text\n%s```\n\n", name, help)
		out.WriteString("| Flag / aliases | 型 | 既定値の表示 | 必須 | 複数値 | 環境変数 |\n|---|---|---|---|---|---|\n")
		for _, f := range cmd.VisibleFlags() {
			doc, ok := f.(cli.DocGenerationFlag)
			if !ok {
				t.Fatalf("flag %v has no documentation interface", f.Names())
			}
			required := false
			if r, ok := f.(cli.RequiredFlag); ok {
				required = r.IsRequired()
			}
			multi := false
			if m, ok := f.(cli.DocGenerationMultiValueFlag); ok {
				multi = m.IsMultiValueFlag()
			}
			value := doc.GetDefaultText()
			if !doc.IsDefaultVisible() {
				value = "(help では省略)"
			}
			fmt.Fprintf(&out, "| %s | %s | %s | %t | %t | %s |\n", docsCell(strings.Join(f.Names(), ", ")), docsCell(doc.TypeName()), docsCell(value), required, multi, docsCell(strings.Join(doc.GetEnvVars(), ", ")))
		}
		out.WriteString("\n")
		for _, child := range cmd.VisibleCommands() {
			visit(append(slices.Clone(path), child.Name))
		}
	}
	visit(nil)
	return append(bytes.TrimRight(out.Bytes(), "\n"), '\n')
}

func protocolReference(t *testing.T) []byte {
	t.Helper()
	var out bytes.Buffer
	out.WriteString("# Bundled protocol reference\n\n<!-- Generated by cmd/bpf-ninja/docs_test.go; do not edit. -->\n\n")
	out.WriteString("`make docs-update` で更新し、`make docs-check` で生成元との差分を検査します。\n")
	out.WriteString("`--dsl-help` と同じ公開 help API と、同梱の vocabulary から生成しています。\n")
	out.WriteString("掲載する field の範囲は help と同じです。\n内部 field のうち help が表示しないものは含めません。\noffset と可変長構造の注記を併せて読んでください。\n")
	out.WriteString("式の書き方と型の詳細は、[DSL 文法](../../dsl-grammar.md)と[型の仕様](../../dsl-types.md)を参照してください。\n\n```text\n")
	if err := kunai.WriteProtocolCatalogue(&out); err != nil {
		t.Fatal(err)
	}
	out.WriteString("```\n\n")
	v, err := dslvocab.Bundled()
	if err != nil {
		t.Fatal(err)
	}
	names := make([]string, 0, len(v))
	for name := range v {
		names = append(names, name)
	}
	slices.Sort(names)
	for _, name := range names {
		fmt.Fprintf(&out, "## %s\n\n```text\n", name)
		if err := kunai.WriteProtocolHelp(&out, name); err != nil {
			t.Fatal(err)
		}
		out.WriteString("```\n\n")
	}
	return append(bytes.TrimRight(out.Bytes(), "\n"), '\n')
}

func TestDocumentation(t *testing.T) {
	for _, tc := range []struct {
		name     string
		generate func(*testing.T) []byte
	}{
		{"commands.md", commandReference},
		{"protocols.md", protocolReference},
	} {
		t.Run(tc.name, func(t *testing.T) {
			got := tc.generate(t)
			if !bytes.Equal(got, tc.generate(t)) {
				t.Fatal("reference generation is not deterministic")
			}
			path := filepath.Join("..", "..", "docs", "ja", "cli", "generated", tc.name)
			if *updateDocs {
				if err := os.MkdirAll(filepath.Dir(path), 0755); err != nil {
					t.Fatal(err)
				}
				if err := os.WriteFile(path, got, 0644); err != nil {
					t.Fatal(err)
				}
			}
			want, err := os.ReadFile(path)
			if err != nil {
				t.Fatalf("%v; run make docs-update", err)
			}
			if !bytes.Equal(got, want) {
				t.Fatalf("%s is stale; run make docs-update and review the diff", path)
			}
		})
	}
}
